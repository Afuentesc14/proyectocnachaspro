    private void enterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_enterActionPerformed
        // 1. Obtener los datos ingresados en las cajas de texto
        String usuarioIngresado = user.getText();
        String passwordIngresada = new String(password.getPassword());

        // 2. Validar si coincide con cualquiera de los dos usuarios permitidos
        boolean esAdmin = usuarioIngresado.equals("admin1234") && passwordIngresada.equals("papas12");
        boolean esAncha = usuarioIngresado.equals("Ancha1234") && passwordIngresada.equals("atol14");

        if (esAdmin || esAncha) {
            // Si es correcto, abrimos el menú principal y cerramos el login
            ComplejoDeportivoLa10 menuPrincipal = new ComplejoDeportivoLa10();
            menuPrincipal.setVisible(true);
            this.dispose();
        } else {
            // Si no coincide, mostramos un error
            javax.swing.JOptionPane.showMessageDialog(this,
                "Usuario o contraseña incorrectos",
                "Error de acceso",
                javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_enterActionPerformed

